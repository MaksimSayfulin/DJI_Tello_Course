import time
from djitellopy import Tello # Импортируем из библиотеки djitellopy модуль Tello


def main():
    tello = Tello() # Создаем специальный объект Tello для управления дроном
    airborne = False # Для отслеживания состояния дрона добавим переменную

    try:
        print("Подключаемся...")
        tello.connect() # Функция позволяющая установить соединение с дроном через WiFi

        battery = tello.get_battery() # Функция возращающая заряд батареи дрона в процентах
        print(f"Заряд: {battery}%") # Вывод f строки и подстановка значения заряда в строку

        if battery < 9: # Контроль заряда батареи
            print("Заряд слишком низкий для учебного полёта. Зарядите аккумулятор.")
            return

        input("Убедитесь, что площадка свободна. Нажмите Enter для взлёта...")

        print("Взлёт!")
        tello.takeoff() # Функция отправляющая команду взлета для дрона
        airborne = True # Дрон теперь в воздухе

        
        time.sleep(3) # Короткое зависание без команд движения.

        print("Посадка...")
        tello.land() # Функция отправляющая команду посадки для дрона
        airborne = False # Дрон сел

        print("Посадка завершена.")

    finally:
        # Попытка штатно посадить дрон, если исключение возникло после взлёта.
        # При потере связи эта команда может не сработать.
        if airborne:
            try:
                tello.land()
            except Exception as exc:
                print(f"Не удалось отправить команду посадки: {exc}")

        tello.end()


if __name__ == "__main__":
    main()
